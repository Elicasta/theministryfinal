export function spanishQuestion(id){return SPANISH_QUESTIONS[id]||null;}
export function translatePublicQuestion(q,stage=null){
 const tr=spanishQuestion(q?.id);if(!tr)return q;
 const out={...q,prompt:tr.prompt,reference:String(q.reference||'').replace(/^Matthew /,'Mateo ')};
 if(Array.isArray(q.choices)&&tr.choices?.length===q.choices.length)out.choices=tr.choices;
 if(Object.prototype.hasOwnProperty.call(q,'correctAnswer'))out.correctAnswer=tr.answer||tr.choices?.[q.choices.indexOf(q.correctAnswer)]||q.correctAnswer;
 if(Object.prototype.hasOwnProperty.call(q,'explanation'))out.explanation=tr.explanation;
 if(Object.prototype.hasOwnProperty.call(q,'application'))out.application=tr.application;
 return out;
}
export function englishChoiceFromSpanish(q,answer){
 const tr=spanishQuestion(q?.id);if(!tr?.choices||!Array.isArray(q?.choices))return null;
 const position=tr.choices.indexOf(answer);
 return position>=0&&position<q.choices.length?q.choices[position]:null;
}
export function translateResponseStats(q,stats){
 const tr=spanishQuestion(q?.id);if(!stats||!tr)return stats;
 const result={...stats};
 if(Array.isArray(stats.responses)&&tr.choices)result.responses=stats.responses.map(r=>{
   const idx=q.choices?.indexOf(r.answer);return {...r,answer:idx>=0?tr.choices[idx]:r.answer};
 });
 if(Array.isArray(stats.fillResponses)&&tr.answer)result.fillResponses=stats.fillResponses.map(r=>({
   ...r,answer:String(r.answer||'').trim().toLocaleLowerCase('es')===String(q.correctAnswer||'').toLocaleLowerCase('en')?tr.answer:r.answer
 }));
 return result;
}
